import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '../..');

const mcpContainersDir = path.join(rootDir, 'mcp/mcp_containers');

const MCP_METADATA = {
  'agmarknet-mcp': { name: 'Agmarknet APMC Mandi Server', desc: 'Live APMC market arrivals, minimum, maximum, and modal commodity prices' },
  'faq': { name: 'Agricultural FAQ Retriever', desc: 'Semantic retrieval of curated FAQ database for common farmer inquiries' },
  'golden_dataset': { name: 'Golden Dataset (GDB) MCP', desc: 'High-confidence vector search over expert-verified golden Q&A dataset' },
  'imd_weather': { name: 'IMD Weather Observation MCP', desc: 'India Meteorological Dept live observation, rain forecasts, and weather alerts' },
  'market': { name: 'National Commodity Market MCP', desc: 'Real-time MSP and commodity trading prices across Indian agricultural markets' },
  'pop': { name: 'Package of Practices (PoP) MCP', desc: 'University recommended crop practices, fertilizer schedules, and pest control' },
  'pop_v2': { name: 'PoP V2 Semantic & Chemical Guard', desc: 'Advanced guideline retrieval with integrated CIBRC banned chemical screening' },
  'review-search-mcp': { name: 'Peer Reviewer Search MCP', desc: 'Semantic matching of incoming questions with existing expert review history' },
  'reviewer_system': { name: 'Reviewer Workbench System MCP', desc: 'Authoring desk support, crop name normalization, and domain routing' },
  'soil-health-mcp': { name: 'Soil Health & Fertilizer MCP', desc: 'District-wise soil macro/micronutrient analysis and urea recommendation calculator' },
  'weather': { name: 'Live Weather Telemetry MCP', desc: 'Hyperlocal temperature, humidity, wind, and precipitation telemetry' },
};

export function generateMcpReport() {
  const containers = fs.readdirSync(mcpContainersDir).filter(f => {
    return fs.statSync(path.join(mcpContainersDir, f)).isDirectory();
  });

  const report = {
    totalServers: containers.length,
    passed: 0,
    failed: 0,
    servers: [],
  };

  for (const c of containers) {
    const dir = path.join(mcpContainersDir, c);
    const meta = MCP_METADATA[c] || { name: c, desc: 'Containerized FastMCP Server' };
    const hasDockerfile = fs.existsSync(path.join(dir, 'Dockerfile'));
    const pyFiles = fs.readdirSync(dir).filter(f => f.endsWith('.py'));

    const isHealthy = hasDockerfile && pyFiles.length > 0;
    if (isHealthy) report.passed++;
    else report.failed++;

    report.servers.push({
      id: c,
      name: meta.name,
      description: meta.desc,
      dockerfile: hasDockerfile ? 'Found' : 'Missing',
      pythonModules: pyFiles.length,
      status: isHealthy ? 'PASS' : 'FAIL',
    });
  }

  return report;
}

export function writeMcpMarkdown(report, outputPath) {
  let md = `# Layer 1: Model Context Protocol (MCP) Server Validation Report\n\n`;
  md += `**Total Servers Validated:** ${report.totalServers} | **Passed:** ${report.passed} | **Failed:** ${report.failed}  \n`;
  md += `**Overall Gate Status:** ${report.failed === 0 ? '🟢 ALL MCP SERVERS VERIFIED (100%)' : '🔴 FAILURES DETECTED'}\n\n`;

  md += `| MCP Server Identifier | Service Name | Python Modules | Dockerfile | Status | Operational Capability |\n`;
  md += `| :--- | :--- | :---: | :---: | :---: | :--- |\n`;

  for (const s of report.servers) {
    const badge = s.status === 'PASS' ? '🟢 PASS' : '🔴 FAIL';
    md += `| \`${s.id}\` | **${s.name}** | ${s.pythonModules} | ${s.dockerfile} | ${badge} | ${s.description} |\n`;
  }

  md += `\n---\n*Report generated by Ajrasakha Layer 1 MCP Gatekeeper*\n`;

  if (outputPath) {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, md, 'utf8');
  }

  const summaryFile = process.env.GITHUB_STEP_SUMMARY;
  if (summaryFile) {
    try {
      fs.appendFileSync(summaryFile, md, 'utf8');
    } catch {}
  }

  return md;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const report = generateMcpReport();
  const md = writeMcpMarkdown(report, path.join(rootDir, 'mcp/reports/mcp-validation-report.md'));
  console.log(md);
}
